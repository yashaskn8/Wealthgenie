import test from 'node:test';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {
  assertUnambiguousGenieProofIndiaPostBundle,
  computeGenieProofSourceDefinitionHash,
  refreshGenieProofIndiaPostPpfEvidence,
} from '../agents/genieProof/genieProofEvidenceRegistryService.js';
import { GENIEPROOF_SOURCE_CATALOG_CANDIDATES } from '../agents/genieProof/genieProofSourceCatalog.js';
import { INDIA_POST_SAVINGS_URL } from '../services/marketData/GovernmentSmallSavingsProvider.js';

// REGRESSION, synthetic adversarial bytes only. These expected refusals are
// authored directly; they are not generated by a financial verifier or an
// independently reviewed real-source financial oracle.
const heading = 'Post Office Small Savings Schemes (w.e.f 01.10.2026 to 31.12.2026)';
const ppfRow = { slNo: '10.', instrument: 'Public Provident Fund Scheme', interestRate: '7.1%', compoundingFrequency: 'Annually' };
const table = rows => `JSON.parse('${JSON.stringify(rows)}')`;
const looseBundle = (rows = [ppfRow], title = heading) => `const archive=${table(rows)};function unrelatedHeading(){return "${title}";}`;

const associationAttacks = [
  ['separate title and table variables', looseBundle()],
  ['current title with stale table metadata', `${looseBundle()};const tablePeriod="01.07.2026 to 30.09.2026";`],
  ['title in user-controlled text', `const userComment="${heading}";const rates=${table([ppfRow])};`],
  ['title in a code comment', `/* ${heading} */const rates=${table([ppfRow])};`],
  ['changed HTML structure without a qualified association', `<h2>${heading}</h2><script>const rates=${table([ppfRow])}</script>`],
  ['unrelated table before PPF table', `${heading};${table([{ slNo: '01.', instrument: 'Other Product', interestRate: '99%' }])};${table([ppfRow])}`],
  ['PPF table before unrelated table', `${heading};${table([ppfRow])};${table([{ slNo: '01.', instrument: 'Other Product', interestRate: '99%' }])}`],
  ['historical and current headings', `${looseBundle()};"Post Office Small Savings Schemes (w.e.f 01.07.2026 to 30.09.2026)";`],
  ['missing PPF', looseBundle([{ slNo: '01.', instrument: 'Other Product', interestRate: '7.1%' }])],
  ['duplicated PPF', looseBundle([ppfRow, { ...ppfRow, slNo: '11.', interestRate: '9.9%' }])],
  ['ambiguous PPF name', looseBundle([{ ...ppfRow, instrument: 'Public Provident Fund Scheme Promotional Account' }])],
  ['malformed calendar date', looseBundle([ppfRow], 'Post Office Small Savings Schemes (w.e.f 31.02.2026 to 30.04.2026)')],
  ['partial quarter', looseBundle([ppfRow], 'Post Office Small Savings Schemes (w.e.f 15.10.2026 to 31.12.2026)')],
  ['cross-calendar-year quarter', looseBundle([ppfRow], 'Post Office Small Savings Schemes (w.e.f 01.10.2026 to 31.03.2027)')],
  ['future quarter', looseBundle([ppfRow], 'Post Office Small Savings Schemes (w.e.f 01.01.2027 to 31.03.2027)')],
  ['expired quarter', looseBundle([ppfRow], 'Post Office Small Savings Schemes (w.e.f 01.07.2026 to 30.09.2026)')],
  ...['7.1% per month', '7.1 basis points', '-7.1%', '101%', 'NaN%', 'Infinity%'].map(value => [
    `unqualified rate unit or value ${value}`, looseBundle([{ ...ppfRow, interestRate: value }]),
  ]),
];

for (const [scenario, bytes] of associationAttacks) {
  test(`India Post source association refuses ${scenario}`, () => {
    assert.throws(() => assertUnambiguousGenieProofIndiaPostBundle(bytes), error => error.code === 'GENIEPROOF_SOURCE_SCHEMA_REJECTED');
  });
}

function sourceFixture() {
  const source = {
    ...GENIEPROOF_SOURCE_CATALOG_CANDIDATES[1],
    qualificationStatus: 'QUALIFIED_FOR_USER_PRESENTATION',
    reusePermissionStatus: 'APPROVED',
    reviewRecord: { reviewedAt: new Date('2026-01-01'), reference: 'TEST_ONLY_SYNTHETIC_FIXTURE', scope: 'TESTS_ONLY' },
  };
  source.definitionHash = computeGenieProofSourceDefinitionHash(source);
  return { findOne() { return { sort() { return this; }, async lean() { return source; } }; } };
}

test('refresh refuses loose provider bytes before any transaction, receipt, or signature', async () => {
  const instruments = ['Post Office Savings Account', '1 Year Time Deposit', '2 Year Time Deposit', '3 Year Time Deposit',
    '5 Year Time Deposit', '5 Year Recurring Deposit Scheme', 'Senior Citizen Savings Scheme', 'Monthly Income Account',
    'National Savings Certificate (VIII Issue)', 'Public Provident Fund Scheme', 'Kisan Vikas Patra', 'Sukanya Samriddhi Account Scheme'];
  const bundle = looseBundle(instruments.map((instrument, index) => ({
    slNo: `${index + 1}.`, instrument, interestRate: '7.1%', compoundingFrequency: 'Annually',
  })));
  const page = '<script src="/_next/static/chunks/rates.js"></script>';
  await assert.rejects(refreshGenieProofIndiaPostPpfEvidence({
    sourceModel: sourceFixture(),
    signer: { signManifest() { assert.fail('unassociated source must never be signed'); } },
    startSession() { assert.fail('unassociated source must not reach persistence'); },
    receiptModel: { create() { assert.fail('unassociated source must not create receipts'); } },
    fetcher: {
      async fetchDocument(url) {
        const body = url === INDIA_POST_SAVINGS_URL ? page : bundle;
        return { requestedUrl: url, url, statusCode: 200, redirectCount: 0,
          contentType: url === INDIA_POST_SAVINGS_URL ? 'text/html' : 'application/javascript',
          body, rawBodySha256: crypto.createHash('sha256').update(body).digest('hex'), retrievedAt: '2026-10-11T12:00:00.000Z' };
      },
    },
    now: () => new Date('2026-10-11T12:00:00.000Z'),
  }), error => error.code === 'GENIEPROOF_SOURCE_SCHEMA_REJECTED');
});

for (const scriptNames of [['current.js', 'archive.js'], ['archive.js', 'current.js']]) {
  test(`refresh rejects multiple candidate bundles in order ${scriptNames.join(', ')}`, async () => {
    const page = scriptNames.map(name => `<script src="/_next/static/chunks/${name}"></script>`).join('');
    const fetchedScripts = [];
    await assert.rejects(refreshGenieProofIndiaPostPpfEvidence({
      sourceModel: sourceFixture(),
      signer: { signManifest() { assert.fail('ambiguous bundles must not be signed'); } },
      parseSourceBundle() { assert.fail('the first candidate bundle must not be selected'); },
      startSession() { assert.fail('ambiguous bundles must not reach persistence'); },
      fetcher: {
        async fetchDocument(url) {
          if (url !== INDIA_POST_SAVINGS_URL) fetchedScripts.push(new URL(url).pathname.split('/').at(-1));
          const body = url === INDIA_POST_SAVINGS_URL ? page : looseBundle();
          return { requestedUrl: url, url, statusCode: 200, redirectCount: 0,
            contentType: url === INDIA_POST_SAVINGS_URL ? 'text/html' : 'application/javascript',
            body, rawBodySha256: crypto.createHash('sha256').update(body).digest('hex'), retrievedAt: '2026-10-11T12:00:00.000Z' };
        },
      },
      now: () => new Date('2026-10-11T12:00:00.000Z'),
    }), error => error.code === 'GENIEPROOF_SOURCE_SCHEMA_REJECTED');
    assert.deepEqual(fetchedScripts, scriptNames, 'all bounded candidate bundles are checked before selection');
  });
}
